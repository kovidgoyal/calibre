import sys
from types import MappingProxyType
from typing import TYPE_CHECKING, NamedTuple

from kgcss import LINT_RULES, LintProblem, LintResult, LintRule, SyntaxProblem, lint

from calibre import prints
from calibre.ebooks.oeb.polish.check.base import ERROR, WARN, BaseError
from calibre.utils.localization import _

if TYPE_CHECKING:
    from collections.abc import Iterable, Mapping

CSS_RULE_ID_PREFIX = 'css:'
# The rule id stylelint used for syntax errors
CSS_SYNTAX_ERROR_RULE_ID = 'CssSyntaxError'

# The secondary options of the rules, as calibre configured them for stylelint
LINT_OPTIONS: Mapping[LintRule, Mapping[str, object]] = MappingProxyType({
    LintRule.DECLARATION_BLOCK_NO_DUPLICATE_PROPERTIES: MappingProxyType({'ignore': ('consecutive-duplicates-with-different-values',)}),
    LintRule.SELECTOR_TYPE_NO_UNKNOWN: MappingProxyType({'ignore': ('custom-elements',)}),
    # panose-1 is allowed in CSS 2.1 and generated by calibre conversion
    LintRule.PROPERTY_NO_UNKNOWN: MappingProxyType({'ignoreProperties': ('panose-1',)}),
})


class CSSBaseError(BaseError):
    FIXABLE_CSS_ERROR = False
    css_rule_id: str | None = None
    # The kgcss rule that found the problem, None for syntax errors
    lint_rule: LintRule | None = None

    @property
    def rule_id(self) -> str:
        if self.css_rule_id:
            return CSS_RULE_ID_PREFIX + self.css_rule_id
        return super().rule_id

    @property
    def rule_name(self) -> str:
        if self.lint_rule is not None:
            return f'CSS: {_(LINT_RULES[self.lint_rule].description)} ({self.lint_rule.value})'
        if self.css_rule_id:
            return f'CSS: {self.css_rule_id}'
        return super().rule_name


class CSSParseError(CSSBaseError):
    level = ERROR
    is_parsing_error = True


class CSSError(CSSBaseError):
    level = ERROR


class CSSWarning(CSSBaseError):
    level = WARN


def disabled_rules_from_skipped_rules(skipped_rules: Iterable[str]) -> frozenset[LintRule]:
    "The lint rules turned off by the skipped rule ids, ignoring the rule names kgcss does not know"
    ans: set[LintRule] = set()
    for rule_id in skipped_rules:
        if rule_id.startswith(CSS_RULE_ID_PREFIX):
            try:
                ans.add(LintRule(rule_id[len(CSS_RULE_ID_PREFIX) :]))
            except ValueError:
                continue  # not a rule that kgcss knows, such as CssSyntaxError
    return frozenset(ans)


def lint_css(css: str, skipped_rules: Iterable[str] = (), fix: bool = False) -> LintResult:
    return lint(css, disabled=disabled_rules_from_skipped_rules(skipped_rules), options=LINT_OPTIONS, fix=fix)


def fix_css_text(css: str, skipped_rules: Iterable[str] = ()) -> str | None:
    "The CSS with all fixable problems fixed, or None if nothing was fixed"
    return lint_css(css, skipped_rules, fix=True).fixed


def utf16_column(css: str, pos: int, column: int) -> int:
    """
    Convert the 1-based column in code points of the position pos in css to
    the 0-based column in UTF-16 code units, which is what Qt uses.
    """
    before = css[max(0, pos - (column - 1)) : pos]
    return len(before) + sum(1 for ch in before if ord(ch) > 0xFFFF)


def translated_message(problem: LintProblem | SyntaxProblem) -> str:
    "The message of the problem in the user interface language"
    try:
        return _(problem.template).format(*problem.args)
    except (IndexError, KeyError, ValueError) as err:
        # A translation with broken placeholders
        prints(f'Translation of the CSS message {problem.template!r} is invalid: {err}', file=sys.stderr)
        return problem.message


def syntax_problem_to_error(sp: SyntaxProblem, job: Job) -> CSSParseError:
    msg = translated_message(sp)
    ans = CSSParseError(msg, job.name, sp.line + job.line_offset, utf16_column(job.css, sp.pos, sp.column))
    ans.css_rule_id = CSS_SYNTAX_ERROR_RULE_ID
    ans.HELP = msg + '. '
    return ans


def problem_to_error(p: LintProblem, job: Job) -> CSSError:
    msg = translated_message(p)
    ans = CSSError(msg, job.name, p.line + job.line_offset, utf16_column(job.css, p.pos, p.column))
    ans.css_rule_id = p.rule.value
    ans.lint_rule = p.rule
    ans.HELP = msg + '. ' + _('See <a href="{}">detailed description</a>.').format(LINT_RULES[p.rule].url) + ' '
    if p.fix is not None:
        ans.FIXABLE_CSS_ERROR = True
        ans.HELP += _('This error will be automatically fixed if you click "Try to correct all fixable errors" below.')
    return ans


class Job(NamedTuple):
    name: str
    css: str
    # The number of lines before the CSS in the file named name
    line_offset: int = 0


def check_css(jobs: Iterable[Job], skipped_rules: Iterable[str] = ()) -> list[BaseError]:
    skipped_rules = tuple(skipped_rules)
    errors: list[BaseError] = []
    for job in jobs:
        result = lint_css(job.css, skipped_rules)
        errors.extend(syntax_problem_to_error(sp, job) for sp in result.syntax_problems)
        errors.extend(problem_to_error(p, job) for p in result.problems)
    return errors


def main() -> None:
    with open(sys.argv[-1], 'rb') as f:
        css = f.read().decode('utf-8')
    for error in check_css([Job(sys.argv[-1], css)]):
        prints(error)


if __name__ == '__main__':
    main()
