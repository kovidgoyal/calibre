class LrsSimpleChar1:
    contents: list
    parent: Parent | None

    def isEmpty(self) -> bool:
        return all(content.isEmpty() for content in self.contents)

    def hasFollowingContent(self) -> bool:
        foundSelf = False
        if self.parent is None:
            return False
        for content in cast('LrsContainer', self.parent).contents:
            if content == self:
                foundSelf = True
            elif foundSelf:
                if not content.isEmpty():
                    return True
        return False


