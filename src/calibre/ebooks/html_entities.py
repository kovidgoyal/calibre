def entity_to_unicode_in_python(match, exceptions=(), encoding='cp1252', result_exceptions=None):
    if result_exceptions is None:
        result_exceptions = {}

    def check(ch):
        return result_exceptions.get(ch, ch)

    ent = match.group(1)
    if ent in exceptions:
        return '&' + ent + ';'
    if ent in {'apos', 'squot'}:  # squot is generated by some broken CMS software
        return check("'")
    if ent == 'hellips':
        ent = 'hellip'
    if ent.startswith('#'):
        try:
            if ent[1] in ('x', 'X'):
                num = int(ent[2:], 16)
            else:
                num = int(ent[1:])
        except Exception:
            return '&' + ent + ';'
        if encoding is None or num > 255:
            return check(my_unichr(num))
        try:
            return check(bytes(bytearray((num,))).decode(encoding))
        except UnicodeDecodeError:
            return check(my_unichr(num))
    from calibre.ebooks.html_entities import html5_entities

    try:
        return check(html5_entities[ent])
    except KeyError:
        pass
    from html.entities import name2codepoint

    try:
        return check(my_unichr(name2codepoint[ent]))
    except KeyError:
        return '&' + ent + ';'


def find_tests():
    import unittest

    class TestHTMLEntityReplacement(unittest.TestCase):
        def test_html_entity_replacement(self):
            from calibre_extensions.fast_html_entities import replace_all_entities

            def t(inp, exp):
                self.assertEqual(exp, replace_all_entities(inp), f'Failed for input: {inp!r}')

            def x(inp, exp):
                self.assertEqual(exp, replace_all_entities(inp, True), f'Failed for input: {inp!r}')

            t('a&#1234;b', 'aӒb')
            t('', '')
            t('a', 'a')
            t('&', '&')
            t('&amp', '&amp')
            t('&amp;', '&')
            t('a&;b &#;c', 'a&;b &#;c')
            t('&lt;', '<')
            t('&amp;&lt;', '&<')
            t('a&amp;b&lt;c', 'a&b<c')
            t('a&acE;b', 'a∾̳b')
            t('a&#1234;b', 'aӒb')
            t('a&#X1234;b', 'aሴb')
            t('a&#x1034fA;b', 'a\U001034fab')
            t('a&#0;b&#x000;c', 'abc')
            x('&amp;&lt;&gt;&apos;&quot;', '&amp;&lt;&gt;&apos;&quot;')

        def test_html_entity_replacement_expanding(self):
            # Some entities decode to more UTF-8 bytes than the entity itself
            from calibre_extensions.fast_html_entities import replace_all_entities

            for name in ('nGt', 'nLt'):
                ent = f'&{name};'
                val = html5_entities[name]
                self.assertGreater(len(val.encode()), len(ent))
                for keep_xml_entities in (False, True):
                    for count in (1, 16, 1000, 300000):
                        for suffix in ('', 'A' * 32):
                            inp = ent * count + suffix
                            exp = val * count + suffix
                            self.assertEqual(exp, replace_all_entities(inp, keep_xml_entities))
                            self.assertEqual(exp.encode(), replace_all_entities(inp.encode(), keep_xml_entities))
                    inp = f'a {ent} b &amp; c &#65; {ent}{ent} d'
                    exp = f'a {val} b {"&amp;" if keep_xml_entities else "&"} c A {val}{val} d'
                    self.assertEqual(exp, replace_all_entities(inp, keep_xml_entities))

    return unittest.defaultTestLoader.loadTestsFromTestCase(TestHTMLEntityReplacement)


def generate_entity_lists():
    import re
    from html import entities as e

    entities: dict = {k.rstrip(';'): e.name2codepoint[k] for k in e.name2codepoint}
    entities.update({k.rstrip(';'): e.html5[k] for k in e.html5})
    # common misspelled entity names
    for k, v in {'squot': "'", 'hellips': entities['hellip']}.items():
        if k not in entities:
            entities[k] = v
    lines = []
    native_lines: list = '''\
struct html_entity { const char *name, *val; }
%%
'''.splitlines()

    def esc_for_c(x):
        if x == '\n':
            return '\\n'
        if x in '''"\\''':
            return '\\' + x
        return x

    for k in sorted(entities):
        v = entities[k]
        lines.append(f"    '{k}': {v!r},")
        native_lines.append(f'"{esc_for_c(k)}","{esc_for_c(v)}"')

    with open(__file__, 'r+b') as f:
        raw = f.read().decode('utf-8')
        pat = re.compile(r'^# ENTITY_DATA {{{.+?^# }}}', flags=re.M | re.DOTALL)
        raw = pat.sub(lambda m: '# ENTITY_DATA {{{\n' + '\n'.join(lines) + '\n# }}}', raw)
        f.seek(0), f.truncate(), f.write(raw.encode('utf-8'))

    import subprocess

    with open(__file__.replace('.py', '.h'), 'wb') as f:
        cp = subprocess.run(
            ['gperf', '--struct-type', '--readonly', '--includes', '--compare-strncmp'],
            input='\n'.join(native_lines).encode(),
            stdout=f,
        )
        if cp.returncode != 0:
            raise SystemExit(cp.returncode)
